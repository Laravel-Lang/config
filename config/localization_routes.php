<?php

declare(strict_types=1);

/**
 * Settings for localized routes and request locale detection.
 *
 * @see https://laravel-lang.com/routes
 */

use LaravelLang\Config\Constants\RouteName;
use LaravelLang\Routes\Middlewares\LocalizationByCookieMiddleware;
use LaravelLang\Routes\Middlewares\LocalizationByHeaderMiddleware;
use LaravelLang\Routes\Middlewares\LocalizationByModelMiddleware;
use LaravelLang\Routes\Middlewares\LocalizationByParameterPrefixMiddlewareMiddleware;
use LaravelLang\Routes\Middlewares\LocalizationBySessionMiddleware;

return [
    /*
     * Names for the locale sources used by the route middleware.
     *
     * `parameter` names the route parameter and the `localizedRoute()` locale key.
     * `header` and `cookie` name the header and cookie read from the request.
     * `session` is the key used to read and store the locale in the session.
     * `column` names the locale attribute on the authenticated Eloquent user.
     *
     * `parameter` and `column` default to `locale`. The others use `Accept-Language`.
     */

    'names' => [
        'parameter' => RouteName::Parameter,
        'header'    => RouteName::Header,
        'cookie'    => RouteName::Cookie,
        'session'   => RouteName::Session,
        'column'    => RouteName::Column,
    ],

    /*
     * Prefix attached to route names for the locale-prefixed group.
     *
     * An empty string uses the default prefix, `localized.`.
     */

    'prefix' => env('LOCALIZATION_PREFIX', 'localized.'),

    /*
     * Redirect requests for the current locale from a named locale-prefixed route
     * to its unprefixed counterpart.
     */

    'redirect' => (bool) env('LOCALIZATION_REDIRECT', false),

    /*
     * Omit the fallback locale segment from URLs generated by `localizedRoute()`.
     */

    'hide' => (bool) env('LOCALIZATION_HIDE', false),

    /*
     * Middleware stacks for `Route::localizedGroup()` and `LocalizationRoute::group()`.
     * A later middleware can override a locale selected by an earlier one.
     */

    'middlewares' => [
        // Routes without a locale prefix.

        'default' => [
            LocalizationByCookieMiddleware::class,
            LocalizationByHeaderMiddleware::class,
            LocalizationBySessionMiddleware::class,
            LocalizationByModelMiddleware::class,
        ],

        // Routes with a locale prefix.

        'prefix' => [
            LocalizationByParameterPrefixMiddlewareMiddleware::class,
            LocalizationByCookieMiddleware::class,
            LocalizationByHeaderMiddleware::class,
            LocalizationBySessionMiddleware::class,
            LocalizationByModelMiddleware::class,
        ],
    ],
];
